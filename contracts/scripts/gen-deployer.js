// One-shot: generate the deployer wallet and write it to .env.
// Run once. After that, the .env holds the keys. Refuses to overwrite.
//
//   node scripts/gen-deployer.js
//
const fs = require("node:fs");
const path = require("node:path");
const { ethers } = require("ethers");

const envPath = path.join(__dirname, "..", ".env");

if (fs.existsSync(envPath)) {
  console.error(`refusing to overwrite existing ${envPath}`);
  console.error("if you really want a new wallet, delete .env first.");
  process.exit(1);
}

const wallet = ethers.Wallet.createRandom();
const mnemonic = wallet.mnemonic ? wallet.mnemonic.phrase : "";

const body = [
  "# Bot Registry deployer wallet — generated by scripts/gen-deployer.js",
  "# Never commit this file. Also upload these values to Proton Pass.",
  "",
  `DEPLOYER_ADDRESS=${wallet.address}`,
  `DEPLOYER_PRIVATE_KEY=${wallet.privateKey}`,
  `DEPLOYER_MNEMONIC=${mnemonic}`,
  "",
  "# RPC endpoints — public defaults; replace with your own if you want.",
  "BASE_SEPOLIA_RPC=https://sepolia.base.org",
  "BASE_MAINNET_RPC=https://mainnet.base.org",
  "",
  "# Etherscan/Basescan API key for verify (optional)",
  "BASESCAN_API_KEY=",
  "",
].join("\n");

fs.writeFileSync(envPath, body, { mode: 0o600 });
fs.chmodSync(envPath, 0o600);

console.log("deployer wallet generated.");
console.log("address:", wallet.address);
console.log(".env written with mode 0600 at:", envPath);
console.log("next: upload DEPLOYER_PRIVATE_KEY + DEPLOYER_MNEMONIC to Proton Pass.");
